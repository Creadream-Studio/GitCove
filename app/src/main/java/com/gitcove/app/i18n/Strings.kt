import androidx.compose.runtime.staticCompositionLocalOf
import java.util.Locale

/**
 * 应用内多语言支持（中文 / English）：
 * - 全部 UI 文案集中于 [Strings]，中文为基准类，[EnStrings] 提供英文覆盖；
 * - 通过 CompositionLocal（[LocalStrings]）下发，切换语言立即全局生效，无需重启；
 * - 首次启动（未手动设置过）为 [AppLanguage.SYSTEM]，按设备系统语言解析。
 */

/** 应用语言设置项：跟随系统 / 中文 / English */
enum class AppLanguage(val code: String) {
    SYSTEM("system"), CHINESE("zh"), ENGLISH("en");

    /** 语言选择器中的展示名：中英均为原生名，仅"跟随系统"交由文案库翻译 */
    val displayName: String
        get() = when (this) {
            CHINESE -> "中文"
            ENGLISH -> "English"
            SYSTEM -> ""
        }

    companion object {
        fun from(code: String?): AppLanguage = entries.firstOrNull { it.code == code } ?: SYSTEM
    }
}

/** 设备系统语言是否为中文 */
fun deviceIsChinese(): Boolean = Locale.getDefault().language == "zh"

/** 按语言设置解析文案实例（SYSTEM 跟随设备语言） */
fun resolveStrings(lang: AppLanguage): Strings {
    val effective = if (lang == AppLanguage.SYSTEM) {
        if (deviceIsChinese()) AppLanguage.CHINESE else AppLanguage.ENGLISH
    } else lang
    return if (effective == AppLanguage.CHINESE) ZhStrings else EnStrings
}

/** 当前生效文案（Composable 中使用：`val S = LocalStrings.current`） */
val LocalStrings = staticCompositionLocalOf<Strings> { ZhStrings }

